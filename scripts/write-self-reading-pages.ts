/**
 * Appends (or refreshes) one illustrated page per board-reading technique (`self.reading.*`, `love.reading.*`,
 * `work.reading.*`; docs/reading-engine/58, 59) in docs/techniques/03, 04 and 05, generated from the catalogue rows so the page cannot drift from the
 * contract. Run: npx tsx scripts/write-self-reading-pages.ts
 */
import fs from 'node:fs';
import path from 'node:path';
import { TECHNIQUES } from '../src/techniques/catalog.js';
import { readerPieceId, techniqueFreshness, techniqueScope } from '../src/techniques/pieces.js';

const VOLUMES: Array<{ prefix: string; file: string }> = [
  { prefix: 'self.reading.', file: 'docs/techniques/03-self-board-illustrations.md' },
  { prefix: 'love.reading.', file: 'docs/techniques/04-love-board-illustrations.md' },
  { prefix: 'work.reading.', file: 'docs/techniques/05-work-board-illustrations.md' },
];
for (const vol of VOLUMES) writeVolume(vol.prefix, vol.file);

function writeVolume(prefix: string, rel: string): void {
const FILE = path.resolve(rel);
const START = `<!-- ${prefix.slice(0, -1)} pages: generated by scripts/write-self-reading-pages.ts -->`;
const rows = TECHNIQUES.filter((t) => t.id.startsWith(prefix));
const md = fs.readFileSync(FILE, 'utf8');
const head = md.includes(START) ? md.slice(0, md.indexOf(START)).trimEnd() : md.trimEnd();
const first = (head.match(/^## Page \d+ of/gm) ?? []).length + 1;
const total = first + rows.length - 1;
const esc = (s: string) => s.replace(/"/g, "'");

const pages = rows.map((t, i) => {
  const fresh = techniqueFreshness(t);
  const readers = t.contract.inputs.map((x) => `\`${readerPieceId(x.section, x.layout)}\` (${x.filter})`).join(' · ');
  const steps = t.algorithm.map((s, j) => `        S${j + 1}["${j + 1}. ${esc(s)}"]`).join('\n');
  const chain = t.algorithm.map((_, j) => `S${j + 1}`).join(' --> ');
  const ins = t.contract.inputs.map((x, j) => `        I${j + 1}["${readerPieceId(x.section, x.layout)}<br/>${esc(x.filter)}"]`).join('\n');
  const insIds = t.contract.inputs.map((_, j) => `I${j + 1}`).join(' & ');
  return `## Page ${first + i} of ${total} — \`${t.id}\`: ${t.title.replace(/^You reading: /, '')}

| Field | Value |
|---|---|
| **Technique ID / Title** | \`${t.id}\` — ${t.title} |
| **Category / Board / Status** | \`${t.category}\` · \`${t.board}\` · \`${t.status}\` |
| **Charts Declared** | ${t.charts.map((c) => `\`${c.source}:${c.id}\``).join(', ')} |
| **Selectors** | \`${JSON.stringify(t.selectors)}\` |
| **Reader Pieces** | ${readers} |
| **Agent Piece** | ${t.agents.length ? t.agents.map((a) => `\`agent:${a}\``).join(', ') : 'none until the spend yes'} (\`system: ${t.contract.system}\`) |
| **Output Piece** | \`output:${t.contract.output}\` |
| **Date-Range Window Cache** | \`freshness: '${fresh}'\` · \`scope: '${techniqueScope(t)}'\` |
| **Code & Source** | \`${t.code}\` (${t.source}) |

\`\`\`mermaid
flowchart LR
    subgraph Inputs["Shared slicers (src/reading/self/slices.ts)"]
${ins}
    end
    subgraph CacheGate["Date-Range Window Cache Gate"]
        GATE{"technique_outputs<br/>freshness: ${fresh}<br/>key includes the reading clock"}
    end
    subgraph Steps["${esc(t.id)}"]
${steps}
        ${chain}
    end
    subgraph Output["Board reading panel"]
        OUT["output:${t.contract.output}<br/>claims with text, detail, certainty, evidence"]
    end
    ${insIds} --> GATE
    GATE -->|"HIT"| OUT
    GATE -->|"MISS"| S1
    S${t.algorithm.length} --> OUT
\`\`\`
`;
});

fs.writeFileSync(FILE, `${head}\n\n---\n\n${START}\n\n${pages.join('\n---\n\n')}`);
console.log(`wrote ${rows.length} pages into ${path.relative(process.cwd(), FILE)}`);
}
